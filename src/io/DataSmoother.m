classdef DataSmoother
    methods (Static)
        function smoothData = fitStrikeToImpliedVolatility(data)
            
            % Alias column names configuration class.
            cnf = ColumnNamesConfig();

            divisibleByFifty = mod(data.(cnf.strike), 50) == 0;

            data = data(divisibleByFifty, :);

            % The strikes and volatilities from market data.
            strikes = data.(cnf.strike);
            volatilities = data.(cnf.impliedVolatility);

            % Piecewise polynomial obtained from a cubic spline of strikes to volatilities.
            piecewisePolynomial = spline(strikes, volatilities);

            % Smoothed data.
            smoothStrike = linspace(min(strikes), max(strikes), 1000);
            smoothVolatility = ppval(piecewisePolynomial, smoothStrike);
            timeToMaturity = data.(cnf.timeToMaturity)(1);
            underlyingMid = data.(cnf.underlyingMid)(1);
            riskFreeRate = data.(cnf.riskFreeRate)(1);
            dividendYield = data.(cnf.dividendYield)(1);

            % Use Black-Scholes pricing function for financial toolbox.
            [callPrice, putPrice] = blsprice(...
                underlyingMid,...
                smoothStrike,...
                riskFreeRate,...
                timeToMaturity,...
                smoothVolatility,...
                dividendYield...
                );
            
            % The smooth data.
            smoothData = struct(...
                'strike', smoothStrike,...
                'volatility', smoothVolatility,...
                'timeToMaturity', timeToMaturity,...
                'underlyingMid', underlyingMid,...
                'riskFreeRate', riskFreeRate,...
                'dividendYield', dividendYield,...
                'callPrice', callPrice,...
                'putPrice', putPrice...
                );

        end
    end
end